# 列表 list 
# 特点:可存储不同类型的元素 ; 元素有序 可重复 可修改
# 存在正向反向两种索引:0~n-1  -1~-n

# 定义:
a = [10,12,60,"ABC",True,3.14]
print(type(a))    #list类型
print(a)

# 删除
del a[1]

# 修改
a[0] = 50
print(a)

# 遍历
for i in a:
    print(i)

# 切片 :序列数据[开始索引(默认为0):结束索引(不包含)(默认为列表长):步长(默认1)] 
# 可使用正向索引也可使用反向索引
b = ["A","B","C","D","E","F"]
print(b)
print(b[:4]) #前四个元素
print(b[0:-1:2])

