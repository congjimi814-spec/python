# 变量  一个变量可以存储不同类型的数据,
num = 111.2
print(num) #111.2
print(type(num)) #<class 'float'>

num = num + 1
print(num) #112.2
print(type(num)) #<class 'float'>

num = "ok"
print(num) #ok
print(type(num)) #<class 'str'>

num = True
print(num) #True
print(type(num)) #<class 'bool'>

num = None
print(num) #None
print(type(num)) #<class 'NoneType'>